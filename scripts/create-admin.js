#!/usr/bin/env node
/**
 * Create an admin login — or promote an existing user — WITHOUT touching any
 * other data.
 *
 *   npm run create:admin -- --email you@hackgru.com --name "Ravikumar S"
 *   npm run create:admin -- --email existing@you.com --promote
 *   npm run create:admin -- --email you@hackgru.com --name "X" --password "chosen"
 *
 * Why this exists: `npm run seed` is the only other way to get an admin, and it
 * calls deleteMany({}) on every collection. On a live database that's a disaster,
 * which is why the seed guard refuses to run there — leaving no way to bootstrap
 * the first admin. This is that way. It only ever adds or updates one user.
 *
 * Safe on production.
 */
import mongoose from 'mongoose';
import crypto from 'crypto';
import { connectDB, isRemoteUri } from '../src/config/db.js';
import { env } from '../src/config/env.js';
import { User } from '../src/models/User.js';

const arg = (name) => {
  const i = process.argv.indexOf(`--${name}`);
  return i > -1 ? process.argv[i + 1] : undefined;
};
const flag = (name) => process.argv.includes(`--${name}`);

const run = async () => {
  const email = (arg('email') || '').toLowerCase().trim();
  const name = arg('name');
  const promote = flag('promote');
  let password = arg('password');

  if (!email) {
    console.error(`
✗ An email is required.

  Create a new admin:
    npm run create:admin -- --email you@hackgru.com --name "Your Name"

  Promote an account you already registered on the site:
    npm run create:admin -- --email you@hackgru.com --promote

  Set your own password instead of a generated one:
    npm run create:admin -- --email you@hackgru.com --name "X" --password "..."
`);
    process.exit(1);
  }

  await connectDB();
  if (isRemoteUri(env.mongoUri)) {
    console.log('\n⚠  Target is a REMOTE database. This script only adds/updates ONE user —');
    console.log('   nothing else is touched.\n');
  }

  // .select('+password') — the field is select:false on the model. Without this
  // the doc loads without it, and setting a new password on a doc that never had
  // the path loaded is fragile.
  const existing = await User.findOne({ email }).select('+password');

  if (existing) {
    if (!promote) {
      console.error(`\n✗ ${email} already exists (role: ${existing.role}) — nothing was changed.`);
      console.error('\n  Running this command twice does NOT reset the password.');
      console.error('  To make this account an admin, and/or set a new password:');
      console.error(`    npm run create:admin -- --email ${email} --promote --password "NewPassword123"`);
      console.error('\n  To check whether a password works:');
      console.error(`    npm run check:login -- --email ${email} --password "..."\n`);
      await mongoose.connection.close();
      process.exit(1);
    }

    const was = existing.role;
    existing.role = 'admin';
    if (password) existing.password = password;
    await existing.save();

    console.log(`\n✓ ${existing.name} <${email}>`);
    console.log(`  Role: ${was} → admin`);
    if (password) {
      // Prove it took, rather than assuming.
      const check = await User.findOne({ email }).select('+password');
      const works = await check.matchPassword(password);
      console.log(`  Password set: ${works ? '✓ verified — this password works' : '✗ FAILED to set'}`);
      if (!works) { await mongoose.connection.close(); process.exit(1); }
    } else {
      console.log('  Password unchanged — log in with the one you already use.');
    }
    console.log('  Sign in at /login — you will land on /admin.\n');
    await mongoose.connection.close();
    return;
  }

  if (promote) {
    // They asked to promote something that doesn't exist. Say THAT, not "--name required".
    console.error(`\n✗ No account with the email "${email}" — there is nothing to promote.`);
    const others = await User.find({ role: { $in: ['admin', 'student'] } })
      .select('email role').sort('-createdAt').limit(5).lean();
    if (others.length) {
      console.error('\n  Accounts that do exist:');
      others.forEach((u) => console.error(`    ${u.email}  (${u.role})`));
    }
    console.error('\n  To CREATE this admin instead, add --name:');
    console.error(`    npm run create:admin -- --email ${email} --name "Your Name"` +
                  (password ? ` --password "..."` : ''));
    console.error('\n  To see every account:  npm run check:login\n');
    await mongoose.connection.close();
    process.exit(1);
  }

  if (!name) {
    console.error(`\n✗ --name is required to create a new admin.\n`);
    console.error(`    npm run create:admin -- --email ${email} --name "Your Name"\n`);
    await mongoose.connection.close();
    process.exit(1);
  }

  // Generated by default: a password you didn't choose is one nobody guessed.
  const generated = !password;
  if (generated) password = crypto.randomBytes(9).toString('base64url');

  const admin = await User.create({ name, email, password, role: 'admin' });

  // Read it back and test the password. Telling you an account works without
  // checking is how you end up locked out with a script that said "✓".
  const verify = await User.findOne({ email }).select('+password');
  const works = await verify.matchPassword(password);

  console.log(`\n✓ Admin created: ${admin.name} <${admin.email}>`);
  console.log(`  Login verified: ${works ? '✓ this password works' : '✗ SOMETHING IS WRONG'}`);
  if (generated) {
    console.log(`\n  Password: ${password}`);
    console.log('  ↑ Shown once. It is hashed in the database and cannot be recovered.');
    console.log('    Change it after your first login.');
  }
  console.log('\n  Sign in at /login — you will land on /admin.\n');
  await mongoose.connection.close();
};

run().catch(async (e) => {
  console.error('\n✗ ' + e.message + '\n');
  await mongoose.connection.close().catch(() => {});
  process.exit(1);
});
